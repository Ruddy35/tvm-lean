#!/usr/bin/env python3
"""boc2lean: turn bags of cells (BOC) into a Lean module of cell literals.

Any contract's code or data, any message, given as a BOC, becomes a Lean term of type
`TvmLean.Cell` that theorems can be stated about, together with the checks that the term is the
cell of the BOC:

* each root becomes `def <name> : Cell`, nested `Cell.mkOrdinary (cellBits! "<hex>") #[refs]`
  literals (`cellBits!`, `TvmLean/Proofs/Contracts/CellLiteral.lean`, elaborates the hex into the
  explicit `#[true, false, ...]` bit array: the term is a closed constructor term, reducible by the
  kernel and by `simp`/`whnf` without unfolding any decoding function). Exotic cells (pruned
  branches, library cells, Merkle proofs and updates) are `Cell.mk` with `special := true` and their
  level mask; a cell referenced more than once becomes its own `def <name>_c<i>`, so the
  term stays a DAG of the BOC's size, and so does a cell whose subtree has more than 1024 bits
  (the elaborator overflows its stack on single terms of some 10^4 bits);
* `def <name>Boc : ByteArray`, the BOC itself;
* `def <name>Hash : Array UInt8`, the representation hash of the root, computed here from the BOC
  (the same algorithm as C++ `vm::DataCell`, all levels; for an ordinary cell
  `sha256(d1 d2 data depths hashes)`);
* `#guard`: the project's BOC reader (`TvmLean.stdBocDeserialize`) reads the BOC as exactly the
  literal (`Cell.beq`; run by the interpreter when the module is built, nothing is added to the
  environment);
* with `--kernel-hash`, `theorem <name>_hash : <name>.hashBytes = <name>Hash := by decide +kernel`:
  the model's hash (`Cell.hashBytes`, SHA-256 in Lean) of the literal is the hash computed here,
  checked by kernel evaluation (no `native_decide`, no axiom). Off by default: the kernel evaluates
  the model's SHA-256 slowly (some seconds per cell; wallet v3's 8 cells take about 100 s).

Usage:

    python3 tools/boc2lean/boc2lean.py --module TvmLean.Proofs.Contracts.Wallet3Code \\
        --out TvmLean/Proofs/Contracts/Wallet3Code.lean \\
        wallet3Code=list:tools/txoracle/contracts.txt#wallet3.code

Each positional argument is `<lean name>=<source>`, the source one of

    list:<file>#<entry>   the line `<entry> <base64 BOC>` of a listing (tools/txoracle/contracts.txt)
    file:<path>           a BOC file: binary, or its base64 or hex text
    b64:<base64>          a BOC in base64
    hex:<hex>             a BOC in hex

Options: `--namespace` (default `TvmLean.Contracts`), `--doc` (a paragraph for the module
docstring), `--kernel-hash`, `--no-guard`. A source ending in `@<i>` takes root `i` of a BOC with
several (default 0). The module imports `TvmLean.Proofs.Contracts.CellLiteral` and `TvmLean.Boc`;
add it to the roots of `lean_lib TvmLeanProofs` in lakefile.lean. The command line is recorded in
the module header, so the module is regenerated by running it again.

Checked on the cells of tools/txoracle/contracts.txt (wallet v3 code and messages, the elector's
code of 100 cells, the configuration contract, DNS data) and on a BOC with every kind of exotic
cell (a Merkle proof and update over a cell with a pruned branch and a library cell): the `#guard`
holds and the hashes equal the model's `Cell.hashBytes` (for wallet v3's code also `fift`'s `hashu`).
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import sys
import textwrap
from dataclasses import dataclass, field

MAX_LEVEL = 3
# the largest subtree (in bits) inlined into its parent's term
INLINE_BITS = 1024


# --- BOC parsing (C++ vm::BagOfCells::deserialize, crypto/vm/boc.cpp) -------------------------

@dataclass
class Cell:
    bits: list[bool]
    refs: list[int]            # indices into the BOC's cell list
    special: bool
    level_mask: int
    # filled by compute_level_info
    depths: list[int] = field(default_factory=list)
    hashes: list[bytes] = field(default_factory=list)
    eff_level: int = 0


def read_be(b: bytes, off: int, n: int) -> int:
    if off + n > len(b):
        raise ValueError(f"BOC: unexpected end of data at {off}")
    return int.from_bytes(b[off:off + n], "big")


def crc32c(data: bytes) -> int:
    crc = 0xFFFFFFFF
    for x in data:
        crc ^= x
        for _ in range(8):
            crc = (crc >> 1) ^ 0x82F63B78 if crc & 1 else crc >> 1
    return crc ^ 0xFFFFFFFF


def parse_boc(data: bytes) -> tuple[list[Cell], list[int]]:
    """Cells (in BOC order) and root indices."""
    magic = read_be(data, 0, 4)
    generic = magic == 0xB5EE9C72
    if magic not in (0xB5EE9C72, 0x68FF65F3, 0xACC3A728):
        raise ValueError(f"BOC: bad magic {magic:#x}")
    flags = data[4]
    has_index = bool(flags & 0x80) if generic else True
    has_crc = bool(flags & 0x40) if generic else magic == 0xACC3A728
    ref_size = flags & 7
    off_size = data[5]
    if not 1 <= ref_size <= 4 or not 1 <= off_size <= 8:
        raise ValueError("BOC: bad sizes")
    cells_n = read_be(data, 6, ref_size)
    roots_n = read_be(data, 6 + ref_size, ref_size)
    absent_n = read_be(data, 6 + 2 * ref_size, ref_size)
    data_size = read_be(data, 6 + 3 * ref_size, off_size)
    if absent_n != 0:
        raise ValueError("BOC: absent cells are not supported")
    pos = 6 + 3 * ref_size + off_size
    if generic:
        roots = [read_be(data, pos + i * ref_size, ref_size) for i in range(roots_n)]
        pos += roots_n * ref_size
    else:
        if roots_n != 1:
            raise ValueError("BOC: an index-form BOC has one root")
        roots = [0]
    if has_index:
        pos += cells_n * off_size
    end = pos + data_size
    if has_crc:
        if crc32c(data[:end]) != int.from_bytes(data[end:end + 4], "little"):
            raise ValueError("BOC: CRC32C mismatch")
    cells: list[Cell] = []
    for idx in range(cells_n):
        d1, d2 = data[pos], data[pos + 1]
        refs_n = d1 & 7
        special = bool(d1 & 8)
        with_hashes = bool(d1 & 16)
        level_mask = d1 >> 5
        if refs_n > 4:
            raise ValueError("BOC: bad reference count")
        pos += 2
        if with_hashes:
            pos += (bin(level_mask).count("1") + 1) * (32 + 2)
        dlen = (d2 >> 1) + (d2 & 1)
        raw = data[pos:pos + dlen]
        pos += dlen
        nbits = dlen * 8
        if d2 & 1:
            last = raw[-1]
            if last & 0x7F == 0:
                raise ValueError("BOC: overlong cell encoding")
            tz = (last & -last).bit_length() - 1
            nbits = (dlen - 1) * 8 + 7 - tz
        bits = [bool((raw[i // 8] >> (7 - i % 8)) & 1) for i in range(nbits)]
        refs = []
        for _ in range(refs_n):
            r = read_be(data, pos, ref_size)
            pos += ref_size
            if not idx < r < cells_n:
                raise ValueError("BOC: bad reference")
            refs.append(r)
        cells.append(Cell(bits, refs, special, level_mask))
    if pos != end:
        raise ValueError("BOC: cell data size mismatch")
    for idx in reversed(range(cells_n)):
        compute_level_info(cells, idx)
    return cells, roots


# --- level masks, depths and hashes (C++ vm::DataCell, crypto/vm/cells/DataCell.cpp) ---------

def get_level(mask: int) -> int:
    return mask.bit_length()


def apply_level(mask: int, level: int) -> int:
    return mask & ((1 << level) - 1)


def is_significant(mask: int, level: int) -> bool:
    return level == 0 or bool((mask >> (level - 1)) & 1)


def hash_i(mask: int) -> int:
    return bin(mask & 7).count("1")


def clamp(c: Cell, level: int) -> int:
    return min(c.eff_level, MAX_LEVEL, level)


def data_bytes(bits: list[bool]) -> bytes:
    n = len(bits)
    padded = list(bits)
    if n % 8:
        padded += [True] + [False] * (7 - n % 8)
    return bytes(int("".join("1" if b else "0" for b in padded[i:i + 8]), 2) for i in range(0, len(padded), 8))


def compute_level_info(cells: list[Cell], idx: int) -> None:
    c = cells[idx]
    kids = [cells[r] for r in c.refs]
    if len(c.bits) > 1023:
        raise ValueError("cell: too many bits")
    ty = 0
    if c.special:
        if len(c.bits) < 8:
            raise ValueError("cell: special cell without its type")
        ty = int("".join("1" if b else "0" for b in c.bits[:8]), 2)
        if ty not in (1, 2, 3, 4):
            raise ValueError(f"cell: bad special type {ty}")
    raw = data_bytes(c.bits)
    depths = [0] * (MAX_LEVEL + 1)
    if ty == 0:
        mask = 0
        for k in kids:
            mask |= k.level_mask
            for lvl in range(MAX_LEVEL + 1):
                depths[lvl] = max(depths[lvl], k.depths[clamp(k, lvl)])
        if kids:
            depths = [d + 1 for d in depths]
    elif ty == 1:  # pruned branch
        if kids or len(c.bits) % 8 or len(c.bits) < 16:
            raise ValueError("cell: bad pruned branch")
        mask = raw[1]
        if get_level(mask) == 0 or get_level(mask) > MAX_LEVEL:
            raise ValueError("cell: bad pruned branch level")
        hn = hash_i(mask)
        if len(raw) != 2 + hn * 34:
            raise ValueError("cell: bad pruned branch length")
        for i in reversed(range(MAX_LEVEL)):
            if is_significant(mask, i + 1):
                o = 2 + hn * 32 + hash_i(apply_level(mask, i)) * 2
                depths[i] = int.from_bytes(raw[o:o + 2], "big")
            else:
                depths[i] = depths[i + 1]
    elif ty == 2:  # library
        if kids or len(c.bits) != 8 * 33:
            raise ValueError("cell: bad library cell")
        mask = 0
    else:  # Merkle proof (3) or update (4)
        nk = 1 if ty == 3 else 2
        if len(kids) != nk or len(c.bits) != 8 * (1 + 34 * nk):
            raise ValueError("cell: bad Merkle cell")
        mask = 0
        for j, k in enumerate(kids):
            if raw[1 + 32 * j:33 + 32 * j] != k.hashes[clamp(k, 0)]:
                raise ValueError("cell: bad Merkle hash")
            if int.from_bytes(raw[1 + 32 * nk + 2 * j:3 + 32 * nk + 2 * j], "big") != k.depths[clamp(k, 0)]:
                raise ValueError("cell: bad Merkle depth")
            mask |= k.level_mask
            for lvl in range(MAX_LEVEL + 1):
                depths[lvl] = max(depths[lvl], k.depths[clamp(k, min(MAX_LEVEL, lvl + 1))] + 1)
        mask >>= 1
    if c.level_mask != mask:
        raise ValueError(f"cell {idx}: level mask {c.level_mask} in the BOC, {mask} computed")
    c.eff_level = get_level(mask)
    merkle = ty in (3, 4)
    hashes: list[bytes] = [b""] * (MAX_LEVEL + 1)
    last = None
    for lvl in range(MAX_LEVEL + 1):
        if not (lvl == MAX_LEVEL or is_significant(mask, lvl + 1)):
            continue
        if ty == 1 and lvl != MAX_LEVEL:
            o = 2 + hash_i(apply_level(mask, lvl)) * 32
            h = raw[o:o + 32]
        else:
            d1 = len(kids) + (8 if c.special else 0) + (apply_level(mask, lvl) << 5)
            d2 = (len(c.bits) // 8) * 2 + (1 if len(c.bits) % 8 else 0)
            msg = bytes([d1, d2])
            msg += hashes[last] if last is not None and ty != 1 else raw
            kl = min(MAX_LEVEL, lvl + 1) if merkle else lvl
            for k in kids:
                msg += k.depths[clamp(k, kl)].to_bytes(2, "big")
            for k in kids:
                msg += k.hashes[clamp(k, kl)]
            h = hashlib.sha256(msg).digest()
        start = 0 if last is None else last + 1
        for j in range(start, lvl + 1):
            hashes[j] = h
        last = lvl
    c.depths = depths
    c.hashes = hashes


def repr_hash(c: Cell) -> bytes:
    return c.hashes[clamp(c, MAX_LEVEL)]


# --- sources ---------------------------------------------------------------------------------

def decode_text(text: str) -> bytes:
    t = "".join(text.split())
    try:
        return bytes.fromhex(t)
    except ValueError:
        return base64.b64decode(t, validate=True)


def load_source(src: str) -> bytes:
    kind, _, rest = src.partition(":")
    if kind == "list":
        path, _, entry = rest.partition("#")
        with open(path, encoding="utf-8") as f:
            for line in f:
                parts = line.split()
                if len(parts) == 2 and parts[0] == entry:
                    return base64.b64decode(parts[1], validate=True)
        raise SystemExit(f"boc2lean: no entry {entry} in {path}")
    if kind == "file":
        with open(rest, "rb") as f:
            raw = f.read()
        if raw[:4] in (b"\xb5\xee\x9c\x72", b"\x68\xff\x65\xf3", b"\xac\xc3\xa7\x28"):
            return raw
        return decode_text(raw.decode("ascii"))
    if kind == "b64":
        return base64.b64decode(rest, validate=True)
    if kind == "hex":
        return bytes.fromhex(rest)
    raise SystemExit(f"boc2lean: unknown source {src!r} (list:, file:, b64:, hex:)")


# --- Lean output -----------------------------------------------------------------------------

def hex_bits(bits: list[bool]) -> str:
    """Fift `x{...}` notation: hex digits, `_` if the last digit is completed by `1 0*`."""
    b = list(bits)
    tag = ""
    if len(b) % 4:
        b += [True] + [False] * (3 - len(b) % 4)
        tag = "_"
    return "".join(f"{int(''.join('1' if x else '0' for x in b[i:i + 4]), 2):X}" for i in range(0, len(b), 4)) + tag


def byte_array(bs: bytes, indent: str, per_line: int = 16) -> str:
    rows = [", ".join(f"0x{x:02x}" for x in bs[i:i + per_line]) for i in range(0, len(bs), per_line)]
    return "#[" + (",\n" + indent + "  ").join(rows) + "]"


class Emitter:
    def __init__(self, name: str, cells: list[Cell], root: int):
        self.name = name
        self.cells = cells
        self.root = root
        # reachable cells and how many references each has among them
        seen: set[int] = set()
        order: list[int] = []

        def visit(i: int) -> None:
            if i in seen:
                return
            seen.add(i)
            for r in cells[i].refs:
                visit(r)
            order.append(i)
        visit(root)
        self.reachable = order                     # children before parents
        self.indeg = {i: 0 for i in order}
        for i in order:
            for r in cells[i].refs:
                self.indeg[r] += 1
        # a cell gets its own definition if it is referenced more than once, or if the term of its
        # subtree is large (the elaborator overflows its stack on single terms of some 10^4 bits)
        self.size: dict[int, int] = {}
        own: set[int] = set()
        for i in order:
            self.size[i] = len(cells[i].bits) + sum(0 if r in own else self.size[r] for r in cells[i].refs)
            if i != root and (self.indeg[i] > 1 or self.size[i] > INLINE_BITS):
                own.add(i)
        self.shared = [i for i in order if i in own]

    def aux_name(self, i: int) -> str:
        return f"{self.name}_c{i}"

    def term(self, i: int, indent: str, top: bool = False) -> str:
        if not top and i in self.shared:
            return self.aux_name(i)
        c = self.cells[i]
        bits = f'cellBits! "{hex_bits(c.bits)}"'
        inner = indent + "  "
        if c.refs:
            refs = "#[\n" + ",\n".join(inner + self.term(r, inner) for r in c.refs) + "]"
        else:
            refs = "#[]"
        if c.special:
            return f"Cell.mk ({bits}) {refs} (special := true) (levelMask := {c.level_mask})"
        return f"Cell.mkOrdinary ({bits}) {refs}"

    def defs(self) -> str:
        out = []
        for i in self.shared:
            refd = f" (referenced {self.indeg[i]} times)" if self.indeg[i] > 1 else ""
            out.append(f"/-- Cell {i} of `{self.name}`{refd}. -/\n"
                       f"def {self.aux_name(i)} : Cell :=\n  {self.term(i, '  ', top=True)}\n")
        n = len(self.reachable)
        h = repr_hash(self.cells[self.root]).hex()
        out.append(f"/-- {n} cell{'s' if n != 1 else ''}, representation hash `{h}`. -/\n"
                   f"def {self.name} : Cell :=\n  {self.term(self.root, '  ', top=True)}\n")
        return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("cells", nargs="+", help="<lean name>=<source>[@<root>]")
    ap.add_argument("--module", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--namespace", default="TvmLean.Contracts")
    ap.add_argument("--doc", default="")
    ap.add_argument("--kernel-hash", action="store_true")
    ap.add_argument("--no-guard", action="store_true")
    args = ap.parse_args()

    body = []
    names = []
    for spec in args.cells:
        name, eq, src = spec.partition("=")
        if not eq or not name.isidentifier():
            raise SystemExit(f"boc2lean: expected <lean name>=<source>, got {spec!r}")
        root_i = 0
        if "@" in src and src.rsplit("@", 1)[1].isdigit():
            src, root_s = src.rsplit("@", 1)
            root_i = int(root_s)
        boc = load_source(src)
        cells, roots = parse_boc(boc)
        if root_i >= len(roots):
            raise SystemExit(f"boc2lean: {src} has {len(roots)} roots")
        em = Emitter(name, cells, roots[root_i])
        root = cells[roots[root_i]]
        names.append(name)
        body.append(f"/-! ## `{name}`: `{src}`" + (f", root {root_i}" if root_i else "") + " -/\n")
        body.append(em.defs())
        body.append(f"/-- The BOC `{name}` was generated from (`{src}`). -/\n"
                    f"def {name}Boc : ByteArray :=\n  ⟨{byte_array(boc, '  ')}⟩\n")
        body.append(f"/-- The representation hash of `{name}`, computed by `tools/boc2lean/boc2lean.py` "
                    f"from the BOC. -/\n"
                    f"def {name}Hash : Array UInt8 :=\n  {byte_array(repr_hash(root), '  ')}\n")
        if not args.no_guard:
            body.append(f"-- the project's BOC reader reads the BOC as exactly the literal\n"
                        f"#guard match stdBocDeserializeMulti {name}Boc with\n"
                        f"  | .ok roots => roots[{root_i}]?.any (· == {name})\n"
                        f"  | .error _ => false\n")
        if args.kernel_hash:
            body.append(f"/-- The model's hash of the literal is the hash of the BOC (kernel evaluation). -/\n"
                        f"theorem {name}_hash : {name}.hashBytes = {name}Hash := by decide +kernel\n")

    def quote(a: str) -> str:
        return a if all(ch.isalnum() or ch in "-_./:#=@" for ch in a) else "'" + a.replace("'", "'\\''") + "'"
    argv, words = sys.argv[1:], []
    while argv:  # an option with its value per line
        a = argv.pop(0)
        if a in ("--module", "--out", "--namespace", "--doc") and argv:
            a = a + " " + quote(argv.pop(0))
        else:
            a = quote(a)
        words.append(a)
    cmd = " \\\n      ".join(["python3 tools/boc2lean/boc2lean.py"] + words)
    def wrap(par: str) -> str:  # no line break inside a `code span`
        parts = par.split("`")
        glued = "`".join(p.replace(" ", "\0") if i % 2 else p for i, p in enumerate(parts))
        return textwrap.fill(glued, 100, break_on_hyphens=False).replace("\0", " ")
    doc = "\n\n".join(wrap(par) for par in args.doc.strip().split("\n\n") if par.strip())
    doc = doc + "\n\n" if doc else ""
    header = f"""import TvmLean.Boc
import TvmLean.Proofs.Contracts.CellLiteral

/-!
# Cell literals: {", ".join(f"`{n}`" for n in names)}

Generated by `tools/boc2lean/boc2lean.py`; do not edit, run again:

    {cmd}

{doc}Each cell is a closed term (`cellBits!` is the explicit bit array of its hex). The check that the
term is the cell of the BOC: `#guard`, the project's BOC reader reads the BOC (`…Boc`) as the literal.
`…Hash` is the representation hash `tools/boc2lean/boc2lean.py` computes from the BOC{" (`…_hash`: the model's hash of the literal, by kernel evaluation)" if args.kernel_hash else ""}.
-/

namespace {args.namespace}

open TvmLean

"""
    text = header + "\n".join(body) + f"\nend {args.namespace}\n"
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
