static std::string hex(td::Slice s) {
  static const char* d = "0123456789abcdef";
  std::string r;
  for (unsigned char c : s) {
    r += d[c >> 4];
    r += d[c & 15];
  }
  return r;
}

static std::string boc_hex(Ref<vm::Cell> c) {
  return hex(vm::std_boc_serialize(std::move(c)).move_as_ok().as_slice());
}

static std::string token(const vm::StackEntry& e) {
  switch (e.type()) {
    case vm::StackEntry::t_null:
      return "N";
    case vm::StackEntry::t_int: {
      auto x = e.as_int();
      return x->is_valid() ? td::dec_string(x) : "NaN";
    }
    case vm::StackEntry::t_cell:
      return "CB:" + boc_hex(e.as_cell());
    case vm::StackEntry::t_slice: {
      vm::CellBuilder cb;
      cb.append_cellslice(*e.as_slice());
      return "SB:" + boc_hex(cb.finalize_novm());
    }
    case vm::StackEntry::t_builder: {
      auto b = e.as_builder();
      if (!b->size() && !b->size_refs()) {
        return "B";
      }
      return "BB:" + boc_hex(b->finalize_copy());
    }
    case vm::StackEntry::t_tuple: {
      auto t = e.as_tuple();
      if (t->empty()) {
        return "T";
      }
      std::string r;
      for (const auto& x : *t) {
        r += token(x) + " ";
      }
      return r + "TUP:" + std::to_string(t->size());
    }
    case vm::StackEntry::t_vmcont:
      return "K";
    default:
      return "?";
  }
}

static bool parse_hex(const std::string& h, std::string& out) {
  if (h.size() % 2) {
    return false;
  }
  out.clear();
  for (size_t i = 0; i < h.size(); i += 2) {
    auto v = [](char c) { return c >= 'a' ? c - 'a' + 10 : c >= 'A' ? c - 'A' + 10 : c - '0'; };
    out += (char)(v(h[i]) * 16 + v(h[i + 1]));
  }
  return true;
}

static Ref<vm::Cell> boc_cell(const std::string& h) {
  std::string bytes;
  if (!parse_hex(h, bytes)) {
    return {};
  }
  // allow_nonzero_level: suite cases put pruned-branch cells (level 1) on the stack
  auto r = vm::std_boc_deserialize(td::Slice{bytes}, false, true);
  return r.is_ok() ? r.move_as_ok() : Ref<vm::Cell>{};
}

// oracle stack tokens (oracle/fif/ton_oracle_runvm.fif, OracleHarness.lean valueToTokens)
static bool parse_tokens(const std::vector<std::string>& toks, std::vector<vm::StackEntry>& st,
                         Ref<vm::Tuple>& c7) {
  for (const auto& t : toks) {
    if (t == "N") {
      st.emplace_back();
    } else if (t == "NaN") {
      st.emplace_back(td::nan_refint());
    } else if (t == "I") {
      st.emplace_back(td::make_refint(0));
    } else if (t == "C") {
      st.emplace_back(Ref<vm::Cell>{vm::CellBuilder{}.finalize_novm()});
    } else if (t == "S") {
      st.emplace_back(vm::load_cell_slice_ref(vm::CellBuilder{}.finalize_novm()));
    } else if (t == "B") {
      st.emplace_back(Ref<vm::CellBuilder>{true});
    } else if (t == "T") {
      st.emplace_back(Ref<vm::Tuple>{true});
    } else if (t == "K") {
      st.emplace_back(Ref<vm::Continuation>{Ref<vm::QuitCont>{true, 0}});
    } else if (t.rfind("CB:", 0) == 0 || t.rfind("SB:", 0) == 0 || t.rfind("BB:", 0) == 0) {
      auto c = boc_cell(t.substr(3));
      if (c.is_null()) {
        return false;
      }
      if (t[0] == 'C') {
        st.emplace_back(c);
      } else if (t[0] == 'S') {
        st.emplace_back(vm::load_cell_slice_ref(c));
      } else {
        Ref<vm::CellBuilder> b{true};
        b.write().append_cellslice(vm::load_cell_slice(c));
        st.emplace_back(b);
      }
    } else if (t.rfind("TUP:", 0) == 0) {
      size_t n = std::stoul(t.substr(4));
      if (n > st.size()) {
        return false;
      }
      std::vector<vm::StackEntry> v(st.end() - n, st.end());
      st.resize(st.size() - n);
      st.emplace_back(Ref<vm::Tuple>{true, std::move(v)});
    } else if (t == "TPUSH") {
      if (st.size() < 2 || !st[st.size() - 2].is_tuple()) {
        return false;
      }
      auto x = st.back();
      st.pop_back();
      auto tup = st.back().as_tuple();
      st.pop_back();
      std::vector<vm::StackEntry> v(tup->begin(), tup->end());
      v.push_back(x);
      st.emplace_back(Ref<vm::Tuple>{true, std::move(v)});
    } else if (t == "SETC7") {
      if (st.empty() || !st.back().is_tuple()) {
        return false;
      }
      c7 = st.back().as_tuple();
      st.pop_back();
    } else {
      auto x = td::dec_string_to_int256(t);
      if (x.is_null() || !x->is_valid()) {
        return false;
      }
      st.emplace_back(x);
    }
  }
  return true;
}

static std::vector<std::string> split(const std::string& s, char sep) {
  std::vector<std::string> r;
  size_t p = 0;
  while (true) {
    size_t q = s.find(sep, p);
    r.push_back(s.substr(p, q == std::string::npos ? std::string::npos : q - p));
    if (q == std::string::npos) {
      break;
    }
    p = q + 1;
  }
  return r;
}

static std::string sig_hex(uint64_t s) {
  char b[17];
  std::snprintf(b, sizeof(b), "%016llx", (unsigned long long)s);
  return b;
}

static std::string sig_str(const Sig& s) {
  return sig_hex(s.seq) + ":" + sig_hex(s.edges) + ":" + sig_hex(s.coarse);
}

// a case line: id \t version \t gas \t code_hex \t tokens; prints id \t exit code \t the windows of
// the target families as <family>:<exact>:<edges>:<coarse>, each distinct one once, space separated
static int run_case(const std::vector<std::string>& cols) {
  Input in;
  in.version = std::stoi(cols[1]);
  in.gas = std::stoll(cols[2]);
  in.code = boc_cell(cols[3]);
  Ref<vm::Tuple> c7;
  std::vector<std::string> toks;
  for (auto& t : split(cols[4], ' ')) {
    if (!t.empty()) {
      toks.push_back(t);
    }
  }
  if (in.code.is_null() || !parse_tokens(toks, in.stack, c7)) {
    std::printf("%s\tERROR\tunparsable case\n", cols[0].c_str());
    return 1;
  }
  int res = run_vm(in, c7);
  std::string sigs;
  std::vector<std::string> seen;  // each distinct window once (loops repeat them)
  for (const auto& s : g_sigs) {
    std::string w = std::string(kForms[s.form].name) + ":" + sig_str(s);
    if (std::find(seen.begin(), seen.end(), w) == seen.end()) {
      seen.push_back(w);
      sigs += (sigs.empty() ? "" : " ") + w;
    }
  }
  std::printf("%s\t%d\t%s\n", cols[0].c_str(), res, sigs.empty() ? "-" : sigs.c_str());
  return 0;
}

// each test or case runs in a forked copy of the process as it is after init_vm: no state of one
// run (the digest counter, caches) reaches the next, as in KLEE where every path starts afresh
static int isolated(const char* id, const std::function<int()>& body) {
  std::fflush(stdout);
  pid_t pid = fork();
  if (pid == 0) {
    int r = body();
    std::fflush(stdout);
    _exit(r);
  }
  int status = 0;
  waitpid(pid, &status, 0);
  if (WIFEXITED(status)) {
    return WEXITSTATUS(status) ? 1 : 0;
  }
  std::printf("%s\tERROR\tcrashed (signal %d)\n", id, WTERMSIG(status));
  return 1;
}

static bool has_int_slot(const FormSpec& f) {
  for (int i = 0; i < f.nslots; i++) {
    if (f.slots[i].kinds & K_INT) {
      return true;
    }
  }
  return false;
}

int main(int argc, char** argv) {
  std::string mode = argc > 1 ? argv[1] : "";
  if (mode == "families") {
    for (const FormSpec& f : kForms) {
      std::printf("%s\t%06x\t%06x\tSG%s\n", f.name, f.lo, f.hi, has_int_slot(f) ? "N" : "");
    }
    return 0;
  }
  if (argc < 4 || (mode != "ktest" && mode != "cases" && mode != "sample")) {
    std::fprintf(stderr,
                 "usage: replay ktest <FAMILY>.<CLASS> <file.ktest>... | replay cases <FAMILY>.<CLASS>|ALL "
                 "<cases.tsv> | replay sample <FAMILY>.<CLASS> <count> | replay families\n");
    return 2;
  }
  if (mode == "cases" && std::strcmp(argv[2], "ALL") == 0) {
    g_all = true;
  } else if (!parse_run(argv[2])) {
    std::fprintf(stderr, "unknown run %s\n", argv[2]);
    return 2;
  }
  SET_VERBOSITY_LEVEL(VERBOSITY_NAME(FATAL));  // td LOG(DEBUG) lines: off
  vm::init_vm(false).ensure();
  warm_up();
  if (mode == "sample") {  // random inputs: id, exit code, signatures, version, gas, code, tokens
    int n = std::atoi(argv[3]), bad = 0;
    for (int i = 0; i < n; i++) {
      std::string id = std::string(argv[2]) + "/r" + std::to_string(i);
      replay::rng = (0x9e3779b97f4a7c15ULL * (i + 1)) ^ (uintptr_t)(g_form - kForms) ^ (unsigned long long)g_class << 40;
      bad += isolated(id.c_str(), [&]() {
        replay::random_mode = true;
        Input in;
        try {
          in = make_input(*g_form);
        } catch (SilentExit&) {
          return 0;
        }
        if (replay::bad) {
          return 0;  // an assumption the random values break
        }
        int res = run_vm(in);
        if (g_sigs.size() != 1) {
          std::printf("%s\tERROR\t%zu windows\n", id.c_str(), g_sigs.size());
          return 1;
        }
        std::string toks;
        for (const auto& e : in.stack) {
          toks += (toks.empty() ? "" : " ") + token(e);
        }
        std::printf("%s\t%d\t%s\t%d\t%lld\t%s\t%s\n", id.c_str(), res, sig_str(g_sigs[0]).c_str(),
                    in.version, in.gas, boc_hex(in.code).c_str(), toks.c_str());
        return 0;
      });
    }
    return bad ? 1 : 0;
  }
  if (mode == "ktest") {
    int bad = 0;
    for (int i = 3; i < argc; i++) {
      bad += isolated(argv[i], [&]() {
        if (!replay::load_ktest(argv[i])) {
          std::printf("%s\tERROR\tunreadable ktest\n", argv[i]);
          return 1;
        }
        Input in;
        try {
          in = make_input(*g_form);
        } catch (SilentExit&) {
          std::printf("%s\tERROR\tsilent exit while building the input\n", argv[i]);
          return 1;
        }
        run_vm(in);
        Sig s = g_sigs.size() == 1 ? g_sigs[0] : Sig{0, 0, 0, -1};
        if (replay::bad) {
          std::printf("%s\tERROR\t%s\n", argv[i], replay::why.c_str());
          return 1;
        }
        uint64_t out = sym<uint64_t>("sig");
        uint64_t out_edges = sym<uint64_t>("esig");
        uint64_t out_coarse = sym<uint64_t>("csig");
        if (replay::bad || out != s.seq || out_edges != s.edges || out_coarse != s.coarse) {
          std::printf("%s\tERROR\tpath differs from KLEE's (KLEE %s, replay %s, windows %zu)\n", argv[i],
                      sig_hex(out).c_str(), sig_hex(s.seq).c_str(), g_sigs.size());
          return 1;
        }
        std::string toks;
        for (const auto& e : in.stack) {
          toks += (toks.empty() ? "" : " ") + token(e);
        }
        // ktest, exact, edges, coarse, version, gas, code, tokens
        std::printf("%s\t%s\t%s\t%s\t%d\t%lld\t%s\t%s\n", argv[i], sig_hex(s.seq).c_str(),
                    sig_hex(s.edges).c_str(), sig_hex(s.coarse).c_str(), in.version, in.gas,
                    boc_hex(in.code).c_str(), toks.c_str());
        return 0;
      });
    }
    return bad ? 1 : 0;
  }
  // cases
  FILE* f = std::fopen(argv[3], "r");
  if (!f) {
    return 2;
  }
  std::string line;
  int c;
  int bad = 0;
  auto flush = [&]() {
    if (line.empty()) {
      return;
    }
    auto cols = split(line, '\t');
    line.clear();
    if (cols.size() < 5) {
      std::printf("%s\tERROR\tbad line\n", cols[0].c_str());
      bad++;
      return;
    }
    bad += isolated(cols[0].c_str(), [&]() { return run_case(cols); });
  };
  while ((c = std::fgetc(f)) != EOF) {
    if (c == '\n') {
      flush();
    } else {
      line += (char)c;
    }
  }
  flush();
  std::fclose(f);
  return bad ? 1 : 0;
}
