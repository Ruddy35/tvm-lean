// KLEE harness for the C++ TVM of the reference (ton @ 3d478cb): one instruction, run through the
// real dispatch (VmState::run on a one-instruction code cell), on a symbolic input of bounded
// shape. Built twice (tools/klee/build.sh):
//
//  * TVM_KLEE_SYMBOLIC: the KLEE entry point. `klee ... harness.bc <FAMILY>.<CLASS>` explores
//    every feasible path of the family under the gas class and writes one .ktest per path.
//  * TVM_KLEE_NATIVE: the replay binary `replay`, linked natively from the same instrumented TON
//    bitcode.
//      replay ktest <RUN> <file.ktest>...  rebuild each test's input (the same code as under
//          KLEE, the values read from the .ktest), run it, check the path signatures against the
//          ones KLEE recorded, print the case: id, signatures, version, gas, code BOC, stack tokens
//      replay cases <RUN|ALL> <cases.tsv>  run cases given as code BOC + oracle stack tokens (from
//          the Lean dumper or from `replay ktest`), print the windows of the instruction under
//          test (ALL: of every instruction) with their family and signatures
//      replay sample <RUN> <n>               n random inputs of the run (a smoke test)
//      replay families                       the families: name, 24-bit opcode range, classes
//
// Families (`kForms`, generated by tools/klee/gen_families.py from tvm_spec_index.json into
// families.inc): one per instruction form, one per opcode range no form has. A family lists its
// code cells (each opcode with its immediate arguments, inline data and references, concrete),
// its stack slots (entry types, and for integers a role, `Role`), its stack depths.
//
// Classes: S = gas limit symbolic in 0..kSmallGasMax, no NaN; G = gas 10^6, no NaN; N = gas 10^6
// and at least one NaN integer on the stack (NaN reaches the oracle through a code prelude,
// Tests/Harness/OracleHarness.lean, that costs gas: large limit only).
//
// Input shape: the global version (0..16, symbolic), the gas limit, the stack entries of the slots
// (type from the slot's set; an integer by its role: symbolic int16, int64, +-2^k+d near the word
// and 257-bit bounds, any 257-bit value, or one of a list of values around the bounds of widths,
// indices, counts; cells, slices and builders of boundary bit lengths with symbolic bits and
// 0/1/3/4 references, a library cell; tuples of boundary sizes; three concrete dictionaries),
// then the code cell and the stack depth (each a path of its own). Entries below the slots are
// concrete integers.
//
// Path signatures: every basic block of the TON code calls tvm_cov(id) or, inside the folded
// functions, tvm_covf(id) (cov_instrument.py: outside namespace vm, the bit-level methods of
// CellSlice and CellBuilder, destructors). VmState::step() calls tvm_klee_step_hook() first, and
// the step ends (tvm_klee_step_end) after the gas check that follows it in run_inner or where
// run_inner/run catch what it threw. Over a window (the step of the instruction under test, the
// one at the start of its cell; with `replay cases ALL`, of every instruction; see Window below)
// the block ids are hashed three ways: the block sequence (exact path), the set of block-to-block
// edges (the path up to loop iteration counts), and the set of edges between the blocks outside
// the folded functions (the coarse, handler-level path: the BigInt, bitstring, refcount and
// library internals folded). Under KLEE the harness ends by constraining symbolic `sig`, `esig`
// and `csig` to them, so each .ktest carries the signatures of its path.
