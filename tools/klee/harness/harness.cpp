constexpr int kForms_n = sizeof(kForms) / sizeof(kForms[0]);
constexpr int kSmallGasMax = 4000;

// a run: a family and a class
static const FormSpec* g_form = nullptr;
static char g_class = 'G';

static const FormSpec* find_form(const std::string& n) {
  for (const FormSpec& f : kForms) {
    if (n == f.name) {
      return &f;
    }
  }
  return nullptr;
}

// "<FAMILY>.<CLASS>"
static bool parse_run(const char* run) {
  std::string r = run;
  size_t dot = r.rfind('.');
  if (dot == std::string::npos || dot + 2 != r.size() || std::strchr("SGN", r[dot + 1]) == nullptr) {
    return false;
  }
  g_form = find_form(r.substr(0, dot));
  g_class = r[dot + 1];
  return g_form != nullptr;
}

// the family of a step's opcode (24 bits, zero-padded as the dispatch reads it), -1 if none
static int form_of_opcode(unsigned op) {
  int lo = 0, hi = kForms_n - 1;
  // kForms is not sorted by opcode: a sorted index, built once
  static std::vector<int> order;
  if (order.empty()) {
    for (int i = 0; i < kForms_n; i++) {
      order.push_back(i);
    }
    std::sort(order.begin(), order.end(), [](int a, int b) { return kForms[a].lo < kForms[b].lo; });
  }
  while (lo <= hi) {
    int m = (lo + hi) / 2;
    const FormSpec& f = kForms[order[m]];
    if (op < f.lo) {
      hi = m - 1;
    } else if (op >= f.hi) {
      lo = m + 1;
    } else {
      return order[m];
    }
  }
  return -1;
}

// ---------------------------------------------------------------- path signatures
// A window is the stretch of execution one signature covers: the step of one instruction (from
// VmState::step to the end of its gas check, or to where the VM catches what it threw).
struct Sig {
  uint64_t seq;     // hash of the sequence of blocks: the exact path
  uint64_t edges;   // hash of the set of block-to-block edges: the path up to loop iteration counts
  uint64_t coarse;  // hash of the set of edges between blocks outside the folded functions
  int form;         // the family of the step's instruction
};
struct Window {
  Sig sig;
  uint32_t prev, prevc;
  uint32_t gen;
  unsigned edge_count;
  bool active;
};
constexpr int kMaxWin = 1;  // one step at a time
static Window g_win[kMaxWin];
static int g_nactive = 0;
static bool g_all = false;  // record the steps of every family (replay cases ALL)
// the instruction under test: the one at the start of the cell with this data (KLEE, replay ktest
// and sample); null: every instruction of the run's family (replay cases <RUN>)
static const unsigned char* g_target_data = nullptr;
static std::vector<Sig> g_sigs;

// each window's edge sets (both kinds in one table, the coarse ones tagged): open addressing,
// cleared by bumping the window's generation
constexpr unsigned kEdgeSlots = 8192;
static uint64_t g_edge_key[kMaxWin][kEdgeSlots];
static uint32_t g_edge_gen[kMaxWin][kEdgeSlots];
static uint32_t g_gen = 0;

static inline uint64_t mix64(uint64_t x) {
  x ^= x >> 33;
  x *= 0xff51afd7ed558ccdULL;
  x ^= x >> 33;
  x *= 0xc4ceb9fe1a85ec53ULL;
  x ^= x >> 33;
  return x;
}

// adds edge e to window w's set; false if it was there
static bool edge_new(int w, uint64_t e) {
  Window& W = g_win[w];
  if (W.edge_count >= kEdgeSlots / 2) {  // more distinct edges than a handler has: fold the rest in
    return true;
  }
  unsigned h = (unsigned)mix64(e) & (kEdgeSlots - 1);
  while (g_edge_gen[w][h] == W.gen) {
    if (g_edge_key[w][h] == e) {
      return false;
    }
    h = (h + 1) & (kEdgeSlots - 1);
  }
  g_edge_gen[w][h] = W.gen;
  g_edge_key[w][h] = e;
  W.edge_count++;
  return true;
}

static inline void cov_exact(int w, uint32_t id) {
  Window& W = g_win[w];
  W.sig.seq = (W.sig.seq ^ id) * 0x100000001b3ULL;
  uint64_t e = ((uint64_t)W.prev << 32) | id;
  W.prev = id;
  if (edge_new(w, e)) {
    W.sig.edges += mix64(e);
  }
}

// a block outside the folded functions
extern "C" void tvm_cov(uint32_t id) {
  if (!g_nactive) {
    return;
  }
  for (int w = 0; w < kMaxWin; w++) {
    if (g_win[w].active) {
      cov_exact(w, id);
      uint64_t c = (1ULL << 63) | ((uint64_t)g_win[w].prevc << 32) | id;
      g_win[w].prevc = id;
      if (edge_new(w, c)) {
        g_win[w].sig.coarse += mix64(c);
      }
    }
  }
}

// a block of a folded function: the exact signatures only
extern "C" void tvm_covf(uint32_t id) {
  if (!g_nactive) {
    return;
  }
  for (int w = 0; w < kMaxWin; w++) {
    if (g_win[w].active) {
      cov_exact(w, id);
    }
  }
}

static void end_window(int w) {
  g_sigs.push_back(g_win[w].sig);
  g_win[w].active = false;
  g_nactive--;
}

static void start_window(int form) {
  for (int w = 0; w < kMaxWin; w++) {
    if (!g_win[w].active) {
      g_win[w] = Window{{0xcbf29ce484222325ULL, 0, 0, form}, 0, 0, ++g_gen, 0, true};
      g_nactive++;
      return;
    }
  }
}

static void end_windows() {
  for (int w = 0; w < kMaxWin; w++) {
    if (g_win[w].active) {
      end_window(w);
    }
  }
}

extern "C" void tvm_klee_step_end() {
  end_windows();
}

// The hook reads the step's opcode without the slice's methods: prefetch_ulong fills the slice's
// bit cache (the dispatch would then take another path through CellSlice), and data() is a virtual
// call into instrumented code (it would show in the windows still open). Recording is off while
// it reads.
extern "C" void tvm_klee_step_hook(const vm::CellSlice* code) {
  int saved = g_nactive;
  g_nactive = 0;
  bool dispatched = code && code->size() > 0;  // else an implicit RET or JMPREF: no instruction
  int start = -1;
  if (dispatched) {
    const unsigned char* d = code->data();
    unsigned pos = code->cur_pos(), n = code->size() < 24 ? code->size() : 24, op = 0;
    for (unsigned i = 0; i < n; i++) {
      op = op << 1 | ((d[(pos + i) >> 3] >> (7 - ((pos + i) & 7))) & 1);
    }
    op <<= 24 - n;
    if (g_all) {
      start = form_of_opcode(op);
    } else if (g_target_data ? d == g_target_data && pos == 0 && code->cur_ref() == 0
                             : g_form && op >= g_form->lo && op < g_form->hi) {  // replay cases <RUN>
      start = (int)(g_form - kForms);
    }
  }
  g_nactive = saved;
  end_windows();
  if (start >= 0) {
    start_window(start);
  }
}

