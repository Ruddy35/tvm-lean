#!/usr/bin/env python3
"""Regenerates Tests/Harness/Gen/CryptoVectors.lean from the vector scripts of this directory:
  python3 tools/crypto/gen_lean_vectors.py > Tests/Harness/Gen/CryptoVectors.lean
(bls_vectors.py needs `pip install py_ecc`)."""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def run(script):
    return subprocess.run([sys.executable, os.path.join(HERE, script)], check=True, capture_output=True,
                          text=True).stdout.splitlines()


def q(s):
    return '"' + ("" if s == "-" else s) + '"'


def table(name, doc, typ, rows):
    body = ",\n".join("  (" + ", ".join(r) + ")" for r in rows)
    return f"/-- {doc} -/\ndef {name} : Array ({typ}) := #[\n{body}\n]\n"


def main():
    ed = [l.split() for l in run("ed25519_vectors.py")]
    ec = [l.split() for l in run("ecdsa_vectors.py")]
    ri = [l.split() for l in run("ristretto_vectors.py")]
    bl = [l.split() for l in run("bls_vectors.py")]
    parts = ["""/-
Generated by tools/crypto/gen_lean_vectors.py (do not edit): test vectors of independent
pure-Python implementations (Ed25519 after RFC 8032; ECDSA over secp256k1 and P-256; ristretto255
after RFC 9496; BLS12-381 from py_ecc). Byte strings are hex; an empty one is "".
-/

namespace Tests.Gen.CryptoVectors
"""]
    parts.append(table("ed25519", "`(name, kind, key, signature, message, strict equation holds)`; see ed25519_vectors.py",
                       "String × String × String × String × String × Bool",
                       [[q(r[0]), q(r[1]), q(r[2]), q(r[3]), q(r[4]), "true" if r[5] == "1" else "false"] for r in ed]))
    parts.append(table("ecrecover", "`(name, hash, v, r, s, recovered key (04 x y) at version 13 or \"\")`",
                       "String × String × Nat × String × String × String",
                       [[q(r[1]), q(r[2]), r[3], q(r[4]), q(r[5]), q(r[6])] for r in ec if r[0] == "ecrecover"]))
    parts.append(table("xonlyTweak", "`(name, x-only key, tweak, resulting key (04 x y) or \"\")`",
                       "String × String × String × String",
                       [[q(r[1]), q(r[2]), q(r[3]), q(r[4])] for r in ec if r[0] == "tweak"]))
    parts.append(table("p256", "`(name, kind, key (33 bytes), signature (r ‖ s), data, valid)`",
                       "String × String × String × String × String × Bool",
                       [[q(r[1]), q(r[2]), q(r[3]), q(r[4]), q(r[5]), "true" if r[6] == "1" else "false"]
                        for r in ec if r[0] == "p256"]))
    parts.append(table("ristretto", "`(name, encoding, valid)`", "String × String × Bool",
                       [[q(r[0]), q(r[1]), "true" if r[2] == "1" else "false"] for r in ri]))
    for kind, name, doc in [("g1", "blsG1", "compressed G1 points (48 bytes)"),
                            ("g2", "blsG2", "compressed G2 points (96 bytes)"),
                            ("msg", "blsMsg", "messages"), ("fp", "blsFp", "field elements (48 bytes)"),
                            ("fp2", "blsFp2", "Fp2 elements (96 bytes)"), ("sk", "blsSk", "secret scalars")]:
        parts.append(table(name, f"`(name, hex)`: {doc}", "String × String",
                           [[q(r[1]), q(r[2])] for r in bl if r[0] == kind]))
    parts.append(table("blsSig", "`(name, public key name, message name, signature)`",
                       "String × String × String × String",
                       [[q(r[1]), q(r[2]), q(r[3]), q(r[4])] for r in bl if r[0] == "sig"]))
    parts.append("end Tests.Gen.CryptoVectors\n")
    print("\n".join(parts), end="")


if __name__ == "__main__":
    main()
